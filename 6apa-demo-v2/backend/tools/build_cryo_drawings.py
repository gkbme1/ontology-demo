def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    from PIL import Image

    OUT.mkdir(parents=True, exist_ok=True)
    for op, (img, spots) in DRAWINGS.items():
        src = SRC_DIR / img
        dst_name = f"{op}_{Path(img).stem}.png"  # 转 256 色调色板 PNG，单文件版内嵌体积更小
        Image.open(src).convert("RGB").quantize(colors=256, method=Image.Quantize.MEDIANCUT).save(OUT / dst_name, optimize=True)
        w, h = Image.open(src).size
        cfg = {"opId": op, "image": dst_name, "width": w, "height": h,
               "source": f"用户提供的 DCS 流程画面截图（{Path(img).stem}）", "note": NOTE,
               "hotspots": [{"name": n, "x": x, "y": y, "w": ww, "h": hh, "note": note, "confirmed": (op, n) not in INFERRED}
                            for n, x, y, ww, hh, note in spots]}
        (OUT / f"{op}.json").write_text(json.dumps(cfg, ensure_ascii=False, indent=1), "utf-8")
    print(f"写出 {len(DRAWINGS)} 张图纸")
    if "--overlay" in argv:
        from PIL import ImageDraw
        scratch = Path(argv[argv.index("--overlay") + 1]) if len(argv) > argv.index("--overlay") + 1 else ROOT / "overlay"
        scratch.mkdir(parents=True, exist_ok=True)
        for op, (img, spots) in DRAWINGS.items():
            im = Image.open(SRC_DIR / img).convert("RGB")
            d = ImageDraw.Draw(im)
            for n, x, y, ww, hh, _ in spots:
                d.rectangle([x, y, x + ww, y + hh], outline=(255, 0, 255), width=3)
            im.save(scratch / f"{op}.png")
    return 0


if __name__ == "__main__":
    sys.exit(main())
