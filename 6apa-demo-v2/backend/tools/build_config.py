HEAD_FILL = PatternFill("solid", fgColor="DDEBF7")


def _sheet(wb: Workbook, title: str, header: list[str], rows: list[tuple]) -> None:
    ws = wb.create_sheet(title)
    ws.append(header)
    for cell in ws[1]:
        cell.font = Font(bold=True)
        cell.fill = HEAD_FILL
    for row in rows:
        ws.append(list(row))
    for col in ws.columns:
        width = max(len(str(c.value or "")) for c in col)
        ws.column_dimensions[col[0].column_letter].width = min(60, max(10, width * 1.6))
        for c in col:
            c.alignment = Alignment(wrap_text=True, vertical="top")


def build(force: bool = False) -> Path:
    if TARGET.exists() and not force:
        print(f"已存在，未覆盖：{TARGET}（--force 覆盖）")
        return TARGET
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    wb.remove(wb.active)
    _sheet(wb, "车间", ["车间编号", "车间名称", "说明", "状态"], WORKSHOP)
    _sheet(wb, "工艺段", ["工艺段编号", "车间编号", "工艺段名称", "顺序", "说明"], SEGMENTS)
    _sheet(wb, "工序", ["工序编号", "工艺段编号", "工序名称", "顺序", "流程画面", "工段编号", "设备匹配(正则)",
                       "子工序(写在图纸上)", "说明", "状态"], OPS)
    _sheet(wb, "未纳入工段", ["工段编号", "工段名称", "原因"], NOT_INCLUDED)
    _sheet(wb, "说明", ["项", "内容"], [
        ("层级", "车间 → 工艺段 → 工序；工序 = 一张 DCS 流程画面（P&ID），子工序写在图纸上，不单独成层"),
        ("设备归属", "按「工段编号」取点表设备；「设备匹配」非空的工序只认领名称匹配的设备，其余归该工段的默认工序（设备匹配为空的那道）"),
        ("设备组", "设备组是文件夹：一个设备组的成员可分属两道工序（如 水解反应釜组 A–F / G–K），各工序下只显示本工序认领的成员"),
        ("状态", "「草案·待工艺确认」的拆分口径需现场确认后改为「已确认」"),
    ])
    wb.save(TARGET)
    print(f"已生成：{TARGET}")
    return TARGET


